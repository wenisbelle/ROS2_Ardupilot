#!/usr/bin/python3
# -*- coding: utf-8 -*-
import os
import shutil

from ament_index_python.packages import get_package_share_directory
from launch import LaunchDescription
from launch.actions import DeclareLaunchArgument, ExecuteProcess, LogInfo, OpaqueFunction
from launch.substitutions import LaunchConfiguration


# Starts ONE ArduPilot SITL instance (arducopter, JSON backend, lock-step with Gazebo).
# It talks to the drone model spawned in Gazebo by UDP (ArduPilotPlugin, port 9002 + 10*instance).
#
# MAVLink ports of instance i (sysid = drone id):
#   SERIAL0  TCP 5760 + 10*i          -> MAVROS (companion computer link, like TELEM2 on the real drone)
#   SERIAL1  UDP -> gcs_udp (14550)   -> QGroundControl (auto-connect, like the telemetry radio)
#   SERIAL2  TCP 5762 + 10*i          -> MAVProxy / Mission Planner / pymavlink scripts
#
# Parameter files (later override earlier):
#   copter.parm (ArduPilot SITL defaults) -> sitl_common.parm -> <frame>.parm
#   -> profile_<profile>.parm -> instance.parm (generated) -> extra_params
def launch_sitl(context):
    name = LaunchConfiguration('name').perform(context)
    instance = int(LaunchConfiguration('instance').perform(context))
    sysid = LaunchConfiguration('sysid').perform(context) or str(instance + 1)
    frame = LaunchConfiguration('frame').perform(context)
    profile = LaunchConfiguration('profile').perform(context)
    home = LaunchConfiguration('home').perform(context)
    extra_params = LaunchConfiguration('extra_params').perform(context)
    speedup = LaunchConfiguration('speedup').perform(context)
    wipe = LaunchConfiguration('wipe').perform(context).lower() in ('true', '1', 'yes')
    gcs_udp = LaunchConfiguration('gcs_udp').perform(context)
    rtl_alt = float(LaunchConfiguration('rtl_alt').perform(context))
    rtl_alt_step = float(LaunchConfiguration('rtl_alt_step').perform(context))
    sitl_dir = os.path.expanduser(LaunchConfiguration('sitl_dir').perform(context))

    ardupilot_home = os.environ.get('ARDUPILOT_HOME', '/opt/ardupilot')
    cfg_dir = os.path.join(get_package_share_directory('flight_controller'), 'config', 'ardupilot')

    param_files = [
        os.path.join(ardupilot_home, 'Tools', 'autotest', 'default_params', 'copter.parm'),
        os.path.join(cfg_dir, 'sitl_common.parm'),
        os.path.join(cfg_dir, f'{frame}.parm'),
        os.path.join(cfg_dir, f'profile_{profile}.parm'),
    ]

    # Working directory of this drone: eeprom.bin (parameters), logs/ (dataflash .BIN logs)
    workdir = os.path.join(sitl_dir, name)
    os.makedirs(workdir, exist_ok=True)

    # Per-drone parameters: staggered RTL altitude so that the swarm does not
    # converge to the same altitude when several drones return home together
    instance_parm = os.path.join(workdir, 'instance.parm')
    drone_rtl_alt_cm = int(round((rtl_alt + rtl_alt_step * instance) * 100.0))
    with open(instance_parm, 'w') as f:
        f.write(f'# generated by flight_controller/sitl.launch.py for {name}\n')
        f.write(f'RTL_ALT_M {drone_rtl_alt_cm / 100.0:.2f}\n')      # ArduPilot >= 4.7 (m)
        f.write(f'RTL_ALT {drone_rtl_alt_cm}\n')                     # ArduPilot <= 4.6 (cm)
    param_files.append(instance_parm)

    for extra in [p.strip() for p in extra_params.split(',') if p.strip()]:
        param_files.append(os.path.abspath(os.path.expanduser(extra)))

    for path in param_files:
        if not os.path.isfile(path):
            raise RuntimeError(f'[sitl {name}] parameter file not found: {path}')

    binary = shutil.which('arducopter') or os.path.join(ardupilot_home, 'build', 'sitl', 'bin', 'arducopter')

    cmd = [binary,
           '--model', 'JSON',
           '--speedup', speedup,
           '--instance', str(instance),
           '--sysid', sysid,
           '--home', home,
           '--defaults', ','.join(param_files),
           '--sim-address', '127.0.0.1',
           '--serial0', 'tcp:0',
           '--serial1', f'udpclient:{gcs_udp}',
           '--serial2', 'tcp:2']
    if wipe:
        cmd.append('--wipe')

    base = 5760 + 10 * instance
    info = (f'[sitl {name}] {frame} instance {instance} sysid {sysid} | JSON udp {9002 + 10 * instance} | '
            f'MAVROS tcp:{base} | QGC udp->{gcs_udp} | GCS tcp:{base + 2} | home {home} | '
            f'RTL_ALT {drone_rtl_alt_cm / 100.0:.1f} m | dir {workdir}')

    return [
        LogInfo(msg=info),
        ExecuteProcess(cmd=cmd, cwd=workdir, output='screen', name=f'sitl_{name}', emulate_tty=True),
    ]


def generate_launch_description():
    return LaunchDescription([
        DeclareLaunchArgument('name', default_value='drone1', description='Drone name (working dir)'),
        DeclareLaunchArgument('instance', default_value='0',
                              description='SITL instance: ports 9002/5760 + 10*instance'),
        DeclareLaunchArgument('sysid', default_value='', description='MAV_SYSID (default instance + 1)'),
        DeclareLaunchArgument('frame', default_value='x500v2', choices=['x500v2', 'hexa'],
                              description='Airframe parameter file (config/ardupilot/<frame>.parm)'),
        DeclareLaunchArgument('profile', default_value='ideal', choices=['ideal', 'realistic'],
                              description='Sensor profile (config/ardupilot/profile_<profile>.parm)'),
        DeclareLaunchArgument('home', default_value='-35.363262,149.165237,584,0',
                              description='lat,lon,alt,heading of the Gazebo world origin'),
        DeclareLaunchArgument('extra_params', default_value='',
                              description='Comma separated extra .parm files (loaded last)'),
        DeclareLaunchArgument('speedup', default_value='1', description='SITL speed-up factor'),
        DeclareLaunchArgument('wipe', default_value='true',
                              description='Wipe eeprom at start (parameters always from the .parm files)'),
        DeclareLaunchArgument('gcs_udp', default_value='127.0.0.1:14550',
                              description='host:port where MAVLink is sent for QGroundControl'),
        DeclareLaunchArgument('rtl_alt', default_value='15.0', description='RTL altitude of instance 0 [m]'),
        DeclareLaunchArgument('rtl_alt_step', default_value='3.0',
                              description='RTL altitude increment per instance [m]'),
        DeclareLaunchArgument('sitl_dir', default_value='~/.ros/ardupilot_sitl',
                              description='Root of the per-drone SITL working directories'),
        OpaqueFunction(function=launch_sitl),
    ])
